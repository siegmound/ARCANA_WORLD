"""Authorial B6I first-segment topology process scope and query semantics.

This module declares model scope only. It does not execute an event detector,
mutate topology, or perform a transition.
"""
from __future__ import annotations

from dataclasses import dataclass
from enum import Enum
from types import MappingProxyType
from typing import Mapping


RIFT_ACTIVATION_HORIZON_YEARS = 27123.405156307464


class FirstSegmentStatus(str, Enum):
    ENABLED = "ENABLED"
    DERIVED_FROM_ENABLED_EVENT = "DERIVED_FROM_ENABLED_EVENT"
    OUT_OF_SCOPE_FOR_FIRST_SEGMENT_MODEL = "OUT_OF_SCOPE_FOR_FIRST_SEGMENT_MODEL"


class EventQueryStatus(str, Enum):
    EVENT_OCCURRED = "EVENT_OCCURRED"
    EVENT_DID_NOT_OCCUR = "EVENT_DID_NOT_OCCUR"
    MODEL_SCOPE_LIMITATION = "MODEL_SCOPE_LIMITATION"
    UNKNOWN = "UNKNOWN"


class UnknownTopologyEventError(KeyError):
    """Raised closed when a newly introduced topology event lacks authority."""


@dataclass(frozen=True)
class TopologyProcess:
    event_class: str
    first_segment_status: FirstSegmentStatus
    authority: str
    detector: str
    horizon_status: str
    future_extension_status: str
    derived_from: str | None = None


@dataclass(frozen=True)
class TopologyProcessRegistry:
    schema: str
    model_scope: str
    topology_hold_rule: str
    processes: Mapping[str, TopologyProcess]
    unknown_event_policy: str

    def get(self, event_class: str) -> TopologyProcess:
        try:
            return self.processes[event_class]
        except KeyError as exc:
            raise UnknownTopologyEventError(
                f"topology event class has no first-segment authority: {event_class}"
            ) from exc

    def classify_observation(self, event_class: str, occurred: bool | None) -> EventQueryStatus:
        process = self.get(event_class)
        if process.first_segment_status is FirstSegmentStatus.OUT_OF_SCOPE_FOR_FIRST_SEGMENT_MODEL:
            return EventQueryStatus.MODEL_SCOPE_LIMITATION
        if occurred is None:
            return EventQueryStatus.UNKNOWN
        return EventQueryStatus.EVENT_OCCURRED if occurred else EventQueryStatus.EVENT_DID_NOT_OCCUR

    def topology_hold_applies(self, elapsed_years: float) -> bool:
        """True strictly before the qualified enabled-event horizon."""
        if elapsed_years < 0:
            raise ValueError("elapsed_years must be non-negative")
        return elapsed_years < RIFT_ACTIVATION_HORIZON_YEARS


def _process(event_class: str, status: FirstSegmentStatus, authority: str,
             detector: str, horizon: str, extension: str,
             derived_from: str | None = None) -> TopologyProcess:
    return TopologyProcess(event_class, status, authority, detector, horizon, extension, derived_from)


