def registry_as_dict(registry: TopologyProcessRegistry = FIRST_SEGMENT_REGISTRY) -> dict[str, object]:
    """Serialize the registry in deterministic event-class order."""
    return {
        "schema": registry.schema,
        "model_scope": registry.model_scope,
        "topology_hold_rule": registry.topology_hold_rule,
        "unknown_event_policy": registry.unknown_event_policy,
        "processes": [
            {
                "event_class": row.event_class,
                "first_segment_status": row.first_segment_status.value,
                "authority": row.authority,
                "detector": row.detector,
                "horizon_status": row.horizon_status,
                "future_extension_status": row.future_extension_status,
                "derived_from": row.derived_from,
            }
            for row in registry.processes.values()
        ],
    }
