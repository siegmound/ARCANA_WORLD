"""Optional complete G3 force-channel candidate on source core + exterior.

Adds ALL EIGHT original core basal facets and explicit core-only GPE increments
to the existing SHA-pinned exterior load; no new constitutive assumptions, no
automatic traction zeros, no 3-D contact, no mechanical equilibrium solve.

This module keeps the original G2/G3 stitched PARTIAL residual intact and
publishes a second, FULL-CHANNEL CANDIDATE residual only for an explicit
engineering scenario. Full input coverage is NOT physical source authority.
"""
from __future__ import annotations

from collections.abc import Mapping
import math

import numpy as np

from experiments.plate58_deforming_explore_v1.g2_g3_source_core_exterior_stitch import need
from experiments.plate58_deforming_explore_v1.g3_force_budget import (
    assemble_explicit_g3_loads, SYNTHETIC_GPE_OWNER, ENGINEERING_AUTHORITY,
)
from experiments.plate58_deforming_explore_v1.g3_gpe_force_accounting import GPE_OWNER
from experiments.plate58_deforming_explore_v1.spherical_exterior import (
    frames_and_cartesian,
)

STATUS = "FULL_G3_EXPLICIT_CANDIDATE_CHANNELS__NOT_PHYSICAL_EQUILIBRIUM"
SCHEMA = "ARCANA_R6_G2_G3_FULL_CORE_EXTERIOR_EXTERNAL_CANDIDATE_V1"


def _ids(mapping, label):
    need(isinstance(mapping, Mapping), label)
    try:
        items={int(k):v for k,v in mapping.items()}
    except (TypeError, ValueError) as exc:
        raise ValueError(label) from exc
    need(len(items)==len(mapping) and all(k>0 for k in items), label)
    return items


def _force(value, count, label):
    try:
        result=np.asarray(value,dtype=float)
    except (TypeError, ValueError) as exc:
        raise ValueError(label) from exc
    need(result.shape==(2*count,) and
         bool(np.all(np.isfinite(result))), label)
    return result.reshape(count,2)


def _project(child, child_ids, global_positions, n):
    result=np.zeros((n,2))
    need(len(child_ids)==len(child), "FULL_G3_SOURCE_INSERTION_COUNT_MISMATCH")
    for j,pid in enumerate(child_ids):
        need(pid in global_positions, "FULL_G3_SOURCE_INSERTION_OWNER_MISSING")
        result[global_positions[pid]]+=child[j]
    return result


def assemble_full_candidate_external(*,stitched,exterior,
    original_parent_node_order,source_core_triangles,source_exterior_triangles,
    source_cut_edges,node_lat_lon_deg,line_tractions_by_edge,
    exterior_basal_tractions_by_triangle,core_basal_tractions_by_triangle,
    exterior_gpe,core_gpe_increment_by_parent_node,velocity_en_by_parent_node,
    fixture_only=False):
    """Account once for exterior cut, ALL basal facets and partitioned GPE.

    Basal traction: explicit tangential xyz Pa on each source triangle,
    using the existing G3 P1 force quadrature and original parent EN DOFs.
    Core GPE: explicit nodal EN force N generated by CORE elements ONLY;
    it adds to, and never overwrites, the original exterior-owned GPE.
    """
    need(isinstance(stitched,Mapping) and isinstance(exterior,Mapping)
         and stitched.get("physical_T1") is None
         and stitched.get("physical_solver_runs")==0
         and stitched.get("full_domain_physical_residual_AVAILABLE") is False
         and exterior.get("physical_T1") is None
         and exterior.get("physical_solver_runs")==0,
         "FULL_G3_PRIOR_SOURCE_ENGINEERING_AUTHORITY_INVALID")
    ids=list(map(int,original_parent_node_order))
    n=len(ids)
    need(n==len(set(ids)) and all(p>0 for p in ids)
         and ids==list(map(int,stitched["original_parent_node_order"])),
         "FULL_G3_ORIGINAL_PARENT_ORDER_MISMATCH")
    core=_ids(source_core_triangles,"FULL_G3_SOURCE_CORE_TRIANGLES_INVALID")
    ext=_ids(source_exterior_triangles,"FULL_G3_SOURCE_EXTERIOR_TRIANGLES_INVALID")
    need(len(core)==8 and bool(ext) and not(set(core)&set(ext))
         and len(core)+len(ext)==stitched["source_original_full_domain_triangle_count"],
         "FULL_G3_CORE_EXTERIOR_TRIANGLE_PARTITION_INVALID")
    core_nodes={int(v) for tri in core.values() for v in tri}
    ext_nodes={int(v) for tri in ext.values() for v in tri}
    ext_order=list(map(int,exterior["source_node_order"]))
    need(len(core_nodes)==9 and len(ext_order)==len(set(ext_order))
         and ext_nodes==set(ext_order)
         and core_nodes|ext_nodes==set(ids)
         and set(map(int,stitched["source_interface_node_ids"]))==
             core_nodes&ext_nodes
         and core_nodes-ext_nodes=={int(stitched["source_core_only_node_id"])},
         "FULL_G3_SOURCE_SHARED_PARENT_OWNERSHIP_INVALID")
    source_sizes={81:(120,32),289:(504,64)}
    if not fixture_only:
        need(n in source_sizes
             and (len(ext),len(source_cut_edges))==source_sizes[n]
             and stitched["source_G2_core_triangle_count"]==8
             and stitched["source_G3_exterior_triangle_count"]==len(ext),
             "FULL_G3_ORIGINAL_SOURCE_SCOPE_COUNTS_INVALID")
    else:
        need(n==11 and len(ext)==2 and len(source_cut_edges)==4
             and stitched.get("fixture_only") is True,
             "FULL_G3_FIXTURE_SCOPE_MUST_BE_EXPLICIT")
    core_tractions=_ids(core_basal_tractions_by_triangle,
                        "FULL_G3_CORE_BASAL_PROVENANCE_REQUIRED")
    ext_tractions=_ids(exterior_basal_tractions_by_triangle,
                       "FULL_G3_EXTERIOR_BASAL_PROVENANCE_REQUIRED")
    need(set(core_tractions)==set(core)
         and set(ext_tractions)==set(ext)
         and not(set(core_tractions)&set(ext_tractions)),
         "FULL_G3_ALL_SOURCE_BASAL_TRIANGLE_LOADS_REQUIRED")
    need(isinstance(exterior_gpe,Mapping)
         and exterior_gpe.get("GPE_force_owner")==GPE_OWNER
         and exterior_gpe.get("mechanical_solve_authorized") is False
         and exterior_gpe.get("physical_T1") is None
         and list(map(int,exterior_gpe["source_interface_node_order"]))==
             ext_order,
         "FULL_G3_EXTERIOR_GPE_OWNER_OR_ORDER_INVALID")
    gpe_ext=_force(exterior_gpe["candidate_GPE_force_vector_N"],
                    len(ext_order),"FULL_G3_EXTERIOR_GPE_FORCE_INVALID")
    core_gpe_rows=_ids(core_gpe_increment_by_parent_node,
                       "FULL_G3_CORE_GPE_SOURCE_REQUIRED")
    need(set(core_gpe_rows)==core_nodes,
         "FULL_G3_NINE_SOURCE_CORE_GPE_RECORDS_REQUIRED")
    core_gpe=np.zeros((len(core_nodes),2))
    core_order=sorted(core_nodes)
    for i,pid in enumerate(core_order):
        row=core_gpe_rows[pid]
        need(isinstance(row,Mapping)
             and row.get("authority")==ENGINEERING_AUTHORITY
             and row.get("GPE_force_owner")==GPE_OWNER
             and row.get("force_channel")=="CORE_TRIANGLE_GPE_INCREMENT_ONLY"
             and isinstance(row.get("source_reference"),str)
             and len(row["source_reference"].strip())>=10,
             "FULL_G3_CORE_GPE_EXPLICIT_SOURCE_OR_OWNER_MISSING")
        core_gpe[i]=_force(row.get("force_en_N"),1,
                          "FULL_G3_CORE_GPE_VALUE_INVALID")[0]
    coords=_ids(node_lat_lon_deg,"FULL_G3_SOURCE_COORDINATES_MISSING")
    velocities=_ids(velocity_en_by_parent_node,
                    "FULL_G3_SOURCE_VELOCITIES_MISSING")
    need(set(coords)==set(velocities)==set(ids),
         "FULL_G3_SOURCE_COORDINATE_VELOCITY_COVERAGE_INVALID")
    ll=np.asarray([coords[i] for i in ids],dtype=float)
    v=np.asarray([velocities[i] for i in ids],dtype=float)
    need(ll.shape==(n,2) and v.shape==(n,2)
         and bool(np.all(np.isfinite(ll))) and bool(np.all(np.isfinite(v))),
         "FULL_G3_COORDINATES_OR_VELOCITY_NONFINITE")
    total_basal={**ext_tractions,**core_tractions}
    # Reuse the same physically dimensioned P1 quadrature as the exterior.
    ext_load=assemble_explicit_g3_loads(
        ext_order,{i:coords[i] for i in ext_order},
        source_cut_edges,line_tractions_by_edge,ext,
        ext_tractions,gpe_ownership=SYNTHETIC_GPE_OWNER)
    full_load=assemble_explicit_g3_loads(
        ids,coords,source_cut_edges,line_tractions_by_edge,
        {**ext,**core},total_basal,
        gpe_ownership=SYNTHETIC_GPE_OWNER)
    ext_baseline=_force(ext_load["candidate_total_nodal_force_N"],
                         len(ext_order),"FULL_G3_EXT_FORCE_SHAPE")
    full_baseline=_force(full_load["candidate_total_nodal_force_N"],n,
                          "FULL_G3_FULL_FORCE_SHAPE")
    exterior_known=_force(exterior["candidate_external_plus_GPE_force_N"],
                           len(ext_order),"FULL_G3_OLD_EXTERIOR_FORCE_INVALID")
    need(bool(np.allclose(ext_baseline+gpe_ext,exterior_known,
                             rtol=1e-12,atol=1e-6)),
         "FULL_G3_ORIGINAL_EXTERIOR_CHANNEL_RECONSTRUCTION_DRIFT")
    pos={pid:i for i,pid in enumerate(ids)}
    known=_project(exterior_known,ext_order,pos,n)
    need(bool(np.allclose(
        known,_force(stitched["known_exterior_external_and_GPE_force_N"],n,
                     "FULL_G3_STITCHED_KNOWN_FORCE_INVALID"),
        rtol=1e-12,atol=1e-6)),
         "FULL_G3_STITCHED_KNOWN_EXTERIOR_DRIFT")
    baseline_ext=_project(ext_baseline,ext_order,pos,n)
    gpe_e=_project(gpe_ext,ext_order,pos,n)
    gpe_c=_project(core_gpe,core_order,pos,n)
    basal_core=full_baseline-baseline_ext
    # Distinguish actual quadrature source contribution, not assumed zero.
    candidate_total=full_baseline+gpe_e+gpe_c
    need(bool(np.allclose(candidate_total,
                          known+basal_core+gpe_c,
                          rtol=1e-12,atol=1e-6)),
         "FULL_G3_FORCE_PARTITION_FAILED")
    internal=_force(stitched["candidate_whole_domain_internal_force_N"],n,
                    "FULL_G3_INTERNAL_FORCE_INVALID")
    partial=_force(stitched["known_PARTIAL_residual_N_NOT_EQUILIBRIUM"],n,
                   "FULL_G3_PARTIAL_RESIDUAL_INVALID")
    need(bool(np.allclose(partial,internal-known,
                             rtol=1e-12,atol=1e-6)),
         "FULL_G3_STITCHED_PARTIAL_RESIDUAL_DRIFT")
    residual=internal-candidate_total
    xyz,radial,east,north=frames_and_cartesian(ll)
    def diagnostics(forces):
        fxyz=east*forces[:,0,None]+north*forces[:,1,None]
        return (np.sum(fxyz,axis=0).tolist(),
                np.sum(np.cross(xyz,fxyz),axis=0).tolist(),
                float(np.sum(forces*v)))
    channels={
        "known_exterior_cut_basal_GPE":known,
        "new_core_basal":basal_core,
        "new_core_GPE":gpe_c,
        "candidate_all_external":candidate_total,
    }
    return {
        "schema":SCHEMA,"status":STATUS,
        "source_original_parent_node_order":ids,
        "source_original_basal_triangles":len(total_basal),
        "source_original_core_triangles":len(core),
        "source_original_exterior_triangles":len(ext),
        "source_external_cut_edges":len(source_cut_edges),
        "source_core_gpe_parent_nodes":core_order,
        "original_external_known_N":known.ravel().tolist(),
        "new_core_basal_increment_N":basal_core.ravel().tolist(),
        "new_core_GPE_increment_N":gpe_c.ravel().tolist(),
        "candidate_full_channel_external_N":candidate_total.ravel().tolist(),
        "candidate_FULL_CHANNEL_residual_N_NOT_EQUILIBRIUM":residual.ravel().tolist(),
        "candidate_partial_to_full_residual_change_N":
            (residual-partial).ravel().tolist(),
        "global_force_xyz_N":{key:diagnostics(val)[0]
                              for key,val in channels.items()},
        "global_torque_xyz_N_m":{key:diagnostics(val)[1]
                                for key,val in channels.items()},
        "virtual_power_W":{key:diagnostics(val)[2]
                           for key,val in channels.items()},
        "all_core_basal_facets_explicit":True,
        "no_core_or_exterior_GPE_double_count":True,
        "core_basal_normal_support_qualified":False,
        "full_domain_physical_residual_AVAILABLE":False,
        "full_domain_mechanical_equilibrium_qualified":False,
        "physical_fault_slip_law_qualified":False,
        "G2_rock_material_and_lab_qualified":False,
        "G3_mantle_cut_traction_sources_qualified":False,
        "mechanical_solve_authorized":False,
        "physical_solver_runs":0,
        "physical_T1":None,
        "canonical_promotion":False,
        "HistoryStore_modified":False,
        "D_024":"ACTIVE",
    }
