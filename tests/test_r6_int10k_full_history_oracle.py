from __future__ import annotations

from copy import deepcopy
import hashlib

import pytest

from arcana_worldsim.r6.geological_surface_microdomain import SUPPORTS
from arcana_worldsim.r6.int10k_full_history_oracle import (
    CLASSIFICATION, SCHEMA, FullHistoryOracleError, _build_query_index,
    canonical_bytes, query_history, verify_oracle, write_new_oracle_bundle,
)
from arcana_worldsim.r6.regional_geological_evolution import (
    SCHEMA as REGIONAL_SCHEMA, seal_regional_checkpoint,
)
from arcana_worldsim.r6.unified_multiphysics_microdomain import seal_unified_checkpoint


def _regional_state(years: int):
    identity = {"fixture": "SYNTHETIC_ONLY"}
    return {
        "schema": REGIONAL_SCHEMA,
        "source_identity": identity,
        "source_identity_sha256": hashlib.sha256(canonical_bytes(identity)).hexdigest(),
        "time_years": years,
        "records": [{"time_year": year, "events": [{"material_id": "MAT-A"}],
                     "cells": [{"cell_id": "CELL-1", "support_id": SUPPORTS[0]}]}
                    for year in range(1, years + 1)],
        "snapshots": [{"time_year": year,
                       "cells": [{"cell_id": "CELL-1", "support_id": SUPPORTS[0],
                                 "substrate": {"material_id": "MAT-A"}}]}
                      for year in range(years + 1)],
    }


def _result(years: int):
    regional = _regional_state(years)
    steps = [{"step": i, "elapsed_years": float(i),
              "material_volumes": {SUPPORTS[0]: [{"material_role_id": "CRUST"}]},
              "deep": {"inventory_j": float(i)}} for i in range(1, years + 1)]
    unified_checkpoint = seal_unified_checkpoint({
        "elapsed_external_steps": years, "records": steps,
    })
    checkpoint = seal_regional_checkpoint(regional, unified_checkpoint=unified_checkpoint)
    return {
        "schema": "SYNTHETIC_RESULT",
        "state": regional,
        "checkpoint": checkpoint,
        "subsurface_unified_result": {
            "configuration": {"segment_external_step_count": years,
                               "elapsed_external_step_count": years},
            "steps": steps,
            "continuation": unified_checkpoint,
            "final": {"time_years": years, "marker": "actual-final-state"},
        },
        "balances": {"water": {"residual": 0.0}, "solid": {"residual": 0.0}},
    }


def _oracle(years: int = 3, split: int = 1):
    cases = {"direct": _result(years), "split_prefix": _result(split),
             "split_resumed": _result(years)}
    source_identity = {"fixture": "SYNTHETIC_ONLY"}
    configuration = {"years": years, "split_at": split,
                     "abs_tol": 1e-8, "rel_tol": 2e-14}
    implementation = {"commit": None, "source_sha256": {},
                      "tracked_source_changes_present": None}
    run_identity = {"source_identity": source_identity,
                    "configuration": configuration, "schema": SCHEMA,
                    "implementation": implementation}
    # The fixture's prefix checkpoint is generated by the exact prefix result.
    body = {
        "schema": SCHEMA,
        "classification": CLASSIFICATION,
        "status": "PASS_FULL_HISTORY_ORACLE_DIRECT_RESTART_PARITY",
        "run_id": "int10k-full-history-" + hashlib.sha256(canonical_bytes(run_identity)).hexdigest()[:24],
        "attempt_id": "fixture-attempt",
        "source_identity": source_identity,
        "implementation_commit": None,
        "implementation_provenance": implementation,
        "configuration": configuration,
        "coverage": {
            "regional_year_records": list(range(1, years + 1)),
            "regional_snapshots": list(range(years + 1)),
            "unified_elapsed_years": [float(i) for i in range(1, years + 1)],
            "split_boundary_year": split,
            "checkpoint_origin": "ACTUAL_SPLIT_PREFIX_RUN_OUTPUT",
        },
        "cases": cases,
        "query_index": _build_query_index(cases),
        "validation": {"fixture": "SYNTHETIC_TEST_ONLY"},
    }
    body["integrity"] = {"algorithm": "SHA256",
                         "canonical_body_sha256": hashlib.sha256(canonical_bytes(body)).hexdigest()}
    return body


def _reseal(oracle):
    body = {key: value for key, value in oracle.items() if key != "integrity"}
    oracle["integrity"] = {"algorithm": "SHA256",
                           "canonical_body_sha256": hashlib.sha256(canonical_bytes(body)).hexdigest()}
    return oracle


def test_complete_oracle_accepts_all_actual_rows_and_checkpoint_boundary():
    verify_oracle(_oracle())


def test_exact_historical_queries_match_direct_and_resumed_cases():
    oracle = _oracle()
    for case in ("direct", "split_resumed"):
        for year in range(4):
            regional = query_history(oracle, case=case, domain="regional",
                                     time_exact=year, position_id="CELL-1")
            assert regional["status"] == "PASS_ARCHIVED_ROWS_ONLY"
            assert all(record["time"] == year for record in regional["records"])
        for year in (1.0, 2.0, 3.0):
            unified = query_history(oracle, case=case, domain="unified",
                                    time_exact=year, support_id=SUPPORTS[0],
                                    material_id="CRUST")
            assert unified["status"] == "PASS_ARCHIVED_ROWS_ONLY"
            assert all(record["time"] == year for record in unified["records"])
    for year in range(4):
        direct = query_history(oracle, case="direct", domain="regional", time_exact=year)
        resumed = query_history(oracle, case="split_resumed", domain="regional", time_exact=year)
        assert [r["record"] for r in direct["records"]] == [r["record"] for r in resumed["records"]]


def test_oracle_detects_payload_corruption():
    oracle = _oracle()
    oracle["cases"]["direct"]["state"]["snapshots"][1]["cells"][0]["substrate"]["material_id"] = "ALTERED"
    with pytest.raises(FullHistoryOracleError, match="ORACLE_DIGEST_MISMATCH"):
        verify_oracle(oracle)


def test_oracle_detects_checkpoint_tampering_even_after_outer_reseal():
    oracle = _oracle()
    oracle["cases"]["split_prefix"]["checkpoint"]["regional_state"]["time_years"] = 2
    _reseal(oracle)
    with pytest.raises(FullHistoryOracleError, match="CHECKPOINT_INTEGRITY_INVALID"):
        verify_oracle(oracle)


def test_oracle_rejects_missing_coverage_after_digest_is_resealed():
    oracle = _oracle()
    oracle["coverage"]["regional_year_records"] = [1, 3]
    _reseal(oracle)
    with pytest.raises(FullHistoryOracleError, match="ORACLE_COVERAGE_INVALID"):
        verify_oracle(oracle)


def test_oracle_rejects_out_of_order_history_even_after_digest_is_resealed():
    oracle = _oracle()
    records = oracle["cases"]["direct"]["state"]["records"]
    records[0], records[1] = records[1], records[0]
    _reseal(oracle)
    with pytest.raises(FullHistoryOracleError, match="REGIONAL_RECORD_COVERAGE_INVALID"):
        verify_oracle(oracle)


def test_oracle_rejects_direct_restart_divergence_even_after_digest_is_resealed():
    oracle = _oracle()
    resumed = oracle["cases"]["split_resumed"]
    resumed["subsurface_unified_result"]["steps"][1]["deep"]["inventory_j"] += 1.0
    unified_checkpoint_state = deepcopy(resumed["checkpoint"]["unified_checkpoint"]["state"])
    unified_checkpoint_state["records"] = resumed["subsurface_unified_result"]["steps"]
    unified_checkpoint = seal_unified_checkpoint(unified_checkpoint_state)
    resumed["subsurface_unified_result"]["continuation"] = unified_checkpoint
    resumed["checkpoint"] = seal_regional_checkpoint(
        resumed["state"], unified_checkpoint=unified_checkpoint)
    oracle["query_index"] = _build_query_index(oracle["cases"])
    _reseal(oracle)
    with pytest.raises(FullHistoryOracleError, match="ORACLE_DIRECT_RESTART_DIVERGENCE"):
        verify_oracle(oracle)


def test_exact_and_range_queries_return_only_archived_records():
    oracle = _oracle()
    exact = query_history(oracle, case="direct", domain="regional", time_exact=1,
                          position_id="CELL-1", support_id=SUPPORTS[0], material_id="MAT-A")
    assert exact["status"] == "PASS_ARCHIVED_ROWS_ONLY"
    assert {row["record_type"] for row in exact["records"]} == {
        "REGIONAL_SNAPSHOT", "REGIONAL_YEAR_RECORD"}
    missing = query_history(oracle, case="direct", domain="unified", time_exact=1.5)
    assert missing == {"status": "TIME_NOT_ARCHIVED", "records": [], "interpolated": False}
    ranged = query_history(oracle, case="direct", domain="unified", time_range=(1.0, 3.0),
                           support_id=SUPPORTS[0], material_id="CRUST")
    assert [row["time"] for row in ranged["records"]] == [1.0, 2.0, 3.0]
    assert ranged["interpolated"] is False


def test_bundle_manifest_hashes_oracle_and_report_and_refuses_collision(tmp_path):
    oracle = _oracle()
    report = {"authority": CLASSIFICATION, "fixture": True}
    destination = tmp_path / "bundle"
    manifest = write_new_oracle_bundle(oracle, destination, report=report)
    assert manifest["completion"] == "ALL_VALIDATION_PASSED"
    assert {item["path"] for item in manifest["members"]} == {
        "FULL_HISTORY_ORACLE.json", "RUN_REPORT.json"}
    for item in manifest["members"]:
        payload = (destination / item["path"]).read_bytes()
        assert hashlib.sha256(payload).hexdigest() == item["sha256"]
        assert len(payload) == item["byte_length"]
    with pytest.raises(FullHistoryOracleError, match="OUTPUT_DIRECTORY_COLLISION"):
        write_new_oracle_bundle(oracle, destination)


def test_nonfinite_or_non_json_values_are_rejected():
    with pytest.raises(FullHistoryOracleError, match="ORACLE_NOT_CANONICAL_JSON"):
        canonical_bytes({"bad": float("nan")})
